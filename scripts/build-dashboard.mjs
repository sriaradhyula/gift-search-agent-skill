import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const load = (path, encoding = "utf8") => readFile(new URL(path, root), encoding);

const [page, css, theme, report, sample, demos, team, chat, share, dashboard, catalogPhoto, christmasPhoto] = await Promise.all([
  load("docs/dashboard.html"),
  load("docs/styles.css"),
  load("docs/theme.js"),
  load("skills/gift-search/scripts/report.mjs"),
  load("docs/sample.js"),
  load("docs/demos.js"),
  load("docs/team.js"),
  load("docs/chat.js"),
  load("docs/share.js"),
  load("docs/dashboard.js"),
  load("docs/assets/catalog.webp", null),
  load("docs/assets/christmas-gifts.webp", null),
]);

// The browser modules use single-line imports and named exports. Inline them in dependency order.
const client = [report, sample, demos, team, chat, share, dashboard].map((source) =>
  source.replace(/^import .*;\r?\n/gm, "").replace(/^export /gm, ""),
).join("\n");
const styles = css
  .replaceAll('url("./assets/catalog.webp")', `url("data:image/webp;base64,${catalogPhoto.toString("base64")}")`)
  .replaceAll('url("./assets/christmas-gifts.webp")', `url("data:image/webp;base64,${christmasPhoto.toString("base64")}")`);
const guide = "https://github.com/sriaradhyula/gift-search-agent-skill#try-it";
const standalone = page
  .replace("<!doctype html>", "<!doctype html>\n<!-- Generated by npm run build:dashboard. -->")
  .replace('<script src="./theme.js"></script>', () => `<script>\n${theme}</script>`)
  .replace('<link rel="stylesheet" href="./styles.css">', () => `<style>\n${styles}</style>`)
  .replaceAll('href="./dashboard.html"', 'href="#main"')
  .replaceAll(/href="\.\/guide\.html(?:#[^"]*)?"/g, `href="${guide}"`)
  .replace('<script src="./assets/markdown-it.min.js"></script>\n  ', "")
  .replace('<script type="module" src="./dashboard.js"></script>', () =>
    `<!-- GIFT_REPORT_DATA -->\n  <script type="module">\n${client}</script>`,
  );

await Promise.all([
  writeFile(new URL("docs/report.js", root), report),
  writeFile(new URL("skills/gift-search/assets/dashboard.html", root), standalone),
]);
